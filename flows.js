/** ساعة بغداد (UTC+3) */
const baghdadHour = () => new Date(Date.now() + 3 * 3600e3).getUTCHours();

function greeting(name) {
  const h = baghdadHour();
  const time = h < 12 ? 'صباح الخير' : h < 17 ? 'مساء الخير' : h < 23 ? 'مساء الخير' : 'أهلاً';
  const first = (name || '').trim().split(/\s+/)[0] || '';
  const clean = /^[\u0600-\u06FFa-zA-Z\s'.-]{2,20}$/.test(first) ? first : '';
  return clean ? `${time} ${clean} 👋` : `${time} 👋`;
}

